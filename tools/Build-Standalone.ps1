#requires -Version 5.1
[CmdletBinding()]
param([string]$OutputPath)
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$root = Split-Path -Parent $PSScriptRoot
if (-not $OutputPath) { $OutputPath = Join-Path $root 'artifacts/W11PostInstall.ps1' }
$module = Import-Module (Join-Path $root 'src/Wpi.psm1') -Force -PassThru
$fingerprint = & $module { Get-WpiFingerprint }
$lines = @('# Generated by tools/Build-Standalone.ps1. Review the source before running.', '$script:WpiAssets = @{')
foreach ($folder in @('catalog','profiles','locales')) {
    foreach ($file in Get-ChildItem -LiteralPath (Join-Path $root $folder) -Filter '*.json' -File | Sort-Object Name) {
        $json = [IO.File]::ReadAllText($file.FullName).TrimEnd()
        if ($json -match "(?m)^'@") { throw "Cannot embed here-string terminator in $($file.Name)." }
        $lines += ('    ''{0}/{1}'' = @''' -f $folder, $file.Name), $json, "'@"
    }
}
$lines += '}', ('$script:WpiBundledFingerprint = ''{0}''' -f $fingerprint)
$core = [IO.File]::ReadAllText((Join-Path $root 'src/Wpi.psm1')) -replace '(?m)^#requires[^\r\n]*\r?\n', '' -replace '(?m)^Export-ModuleMember[^\r\n]*\r?\n?', ''
$lines += $core
foreach ($file in @('src/Menu.ps1','src/Wizard.ps1')) { $lines += [IO.File]::ReadAllText((Join-Path $root $file)) }
$start = [IO.File]::ReadAllText((Join-Path $root 'Start.ps1'))
$loaders = [regex]::Matches($start, '(?ms)^    # BEGIN SOURCE LOADER\r?\n.*?^    # END SOURCE LOADER[^\r\n]*')
if ($loaders.Count -ne 1) { throw 'Expected exactly one source loader block.' }
$loader = $loaders[0]
$bundle = $start.Remove($loader.Index, $loader.Length).Insert($loader.Index, ($lines -join "`n"))
$tokens = $null; $errors = $null
$null = [Management.Automation.Language.Parser]::ParseInput($bundle, [ref]$tokens, [ref]$errors)
if ($errors.Count) { throw ($errors | Out-String) }
$fullPath = [IO.Path]::GetFullPath($OutputPath)
$null = [IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($fullPath))
[IO.File]::WriteAllText($fullPath, ($bundle -replace '\r?\n', "`r`n"), (New-Object Text.UTF8Encoding($true)))
Get-Item -LiteralPath $fullPath
